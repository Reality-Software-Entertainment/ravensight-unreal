#!/usr/bin/env python3
# Turns the platform's shared scrub fixture (Source/Ravensight/Private/Tests/
# Fixtures/scrub-vectors.json, copied unchanged from the platform's
# docs/errors/scrub-vectors.json) into RavensightScrubVectors.inl, which
# RavensightErrorCapture.spec.cpp includes. The spec then runs every case in
# the editor and under Tools/host-check alike.
#
#   python3 Tools/scrub-vectors/generate.py          writes the .inl
#   python3 Tools/scrub-vectors/generate.py --check  fails when it is stale
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TESTS = os.path.join(ROOT, 'Source', 'Ravensight', 'Private', 'Tests')
SOURCE = os.path.join(TESTS, 'Fixtures', 'scrub-vectors.json')
TARGET = os.path.join(TESTS, 'RavensightScrubVectors.inl')

def literal(text):
    if any(ord(c) > 126 or (ord(c) < 32 and c not in '\n\t') for c in text):
        sys.exit('scrub-vectors: non ASCII or control text needs a TEXT() literal; extend the generator')
    return json.dumps(text)

with open(SOURCE, encoding='utf-8') as f:
    data = json.load(f)

lines = [
    '// Generated by Tools/scrub-vectors/generate.py from Fixtures/scrub-vectors.json',
    '// (version %d). Do not edit: change the fixture and run the generator.' % data['version'],
    '',
]
for case in data['cases']:
    lines.append('{ %s, %s, %s },' % (literal(case['name']), literal(case['in']), literal(case['out'])))
text = '\n'.join(lines) + '\n'

if '--check' in sys.argv:
    current = open(TARGET, encoding='utf-8').read() if os.path.exists(TARGET) else ''
    if current != text:
        sys.exit('RavensightScrubVectors.inl is stale: run python3 Tools/scrub-vectors/generate.py')
    print('scrub vectors: %d cases, generated file is current' % len(data['cases']))
else:
    with open(TARGET, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %d cases' % len(data['cases']))
