#!/usr/bin/env python3
# Turns the platform's identify fixture (Source/Ravensight/Private/Tests/
# Fixtures/identify-vectors.json, copied unchanged from the platform's
# docs/identify/identify-vectors.json) into RavensightIdentifyVectors.inl,
# which RavensightIdentify.spec.cpp includes, so the spec runs every case in
# the editor and under Tools/host-check alike. Text is UTF-8 in std::string,
# written as octal escapes, so no case needs a TEXT() literal.
#
#   python3 Tools/identify-vectors/generate.py          writes the .inl
#   python3 Tools/identify-vectors/generate.py --check  fails when it is stale
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
TESTS = os.path.join(ROOT, 'Source', 'Ravensight', 'Private', 'Tests')
SOURCE = os.path.join(TESTS, 'Fixtures', 'identify-vectors.json')
TARGET = os.path.join(TESTS, 'RavensightIdentifyVectors.inl')

def literal(text):
    out = []
    for byte in text.encode('utf-8'):
        c = chr(byte)
        if 32 <= byte < 127 and c not in '"\\?':
            out.append(c)
        else:
            out.append('\\%03o' % byte)
    return '"' + ''.join(out) + '"'

with open(SOURCE, encoding='utf-8') as f:
    data = json.load(f)

def first_send(step):
    sends = step['expect'].get('sends') or []
    return sends[0]['accountHash'] if sends else ''

def stored(step):
    value = step['expect'].get('stored')
    return value['accountHash'] if isinstance(value, dict) else ''

accept = [c for c in data['accept'] if isinstance(c['accountId'], str)]
refuse = [c for c in data['refuse'] if isinstance(c['accountId'], str)]
differ = data['salts_differ']

lines = [
    '// Generated by Tools/identify-vectors/generate.py from Fixtures/identify-vectors.json',
    '// (version %d). Do not edit: change the fixture and run the generator.' % data['version'],
    '// C++ takes text only, so the integer accept case (%d) and the null and fraction' % (len(data['accept']) - len(accept)),
    '// refuse cases (%d) are left out here.' % (len(data['refuse']) - len(refuse)),
    '',
    'namespace RavensightIdentifyVectors',
    '{',
    '\tconstexpr int Version = %d;' % data['version'],
    '\tconstexpr const char* Salt = %s;' % literal(data['salt']),
    '\tconstexpr int MaxBytes = %d;' % data['max_bytes'],
    '',
    '\tstruct FAccept { const char* Note; const char* AccountId; const char* Wire; const char* PlayerId; };',
    '\tconstexpr FAccept Accept[] = {',
]
for c in accept:
    lines.append('\t\t{ %s, %s, %s, %s },' % (literal(c['note']), literal(c['accountId']), literal(c['wire']), literal(c['playerId'])))
lines += [
    '\t};',
    '',
    '\tstruct FRefuse { const char* Note; const char* AccountId; const char* Reason; };',
    '\tconstexpr FRefuse Refuse[] = {',
]
for c in refuse:
    lines.append('\t\t{ %s, %s, %s },' % (literal(c['note']), literal(c['accountId']), literal(c['reason'])))
lines += [
    '\t};',
    '',
    '\tconstexpr const char* DifferAccountId = %s;' % literal(differ['accountId']),
    '\tconstexpr const char* DifferSaltA = %s;' % literal(differ['salt_a']),
    '\tconstexpr const char* DifferWireA = %s;' % literal(differ['wire_a']),
    '\tconstexpr const char* DifferSaltB = %s;' % literal(differ['salt_b']),
    '\tconstexpr const char* DifferWireB = %s;' % literal(differ['wire_b']),
    '',
    '\t/** The sequence, one row a step: its text, the first expected send and the stored hash ("" for none). */',
    '\tstruct FStep { const char* Step; const char* Send; const char* Stored; };',
    '\tconstexpr FStep Sequence[] = {',
]
for s in data['sequence']:
    lines.append('\t\t{ %s, %s, %s },' % (literal(s['step']), literal(first_send(s)), literal(stored(s))))
lines += ['\t};', '}', '']
text = '\n'.join(lines)

if '--check' in sys.argv:
    current = open(TARGET, encoding='utf-8').read() if os.path.exists(TARGET) else ''
    if current != text:
        sys.exit('RavensightIdentifyVectors.inl is stale: run python3 Tools/identify-vectors/generate.py')
    print('identify vectors: %d accept, %d refuse, %d steps, generated file is current' % (len(accept), len(refuse), len(data['sequence'])))
else:
    with open(TARGET, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %d accept, %d refuse, %d steps' % (len(accept), len(refuse), len(data['sequence'])))
